"""Пример плагина для вашей программы. Скопируйте файл, уберите «_» из имени (например, my_app.py) — и Карина подхватит его при запуске.

Плагин — это функция register(api). Внутри описываются команды: имя, описание, примеры фраз и регулярные выражения.
Фраза приходит в нижнем регистре, без знаков препинания и без имени «Карина». Функция возвращает текст, который Карина произнесёт.
"""
import urllib.request


def register(api):
    @api.command(
        "my_app_record", "Включить запись в моей программе",
        ["включи запись в миксере"],
        r"^(?:включи|начни)\s+запись(?:\s+в\s+миксере)?$",
    )
    def _record(ctx):
        # Вариант 1: у программы есть локальный HTTP-API
        # urllib.request.urlopen("http://127.0.0.1:8080/api/record/start", timeout=3).read()
        # Вариант 2: сочетание клавиш
        # api.winutil.hotkey("ctrl", "shift", "r")
        return "Запись включена."

    @api.command(
        "my_app_scene", "Переключить сцену",
        ["сцена игра"],
        r"^сцена\s+(?P<name>.+)$", llm_args="name",
    )
    def _scene(ctx, name):
        # name — то, что сказали после слова «сцена»
        return f"Переключаю на сцену {name}."
