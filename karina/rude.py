def is_command_like(rest: str) -> bool:
    """Фраза похожа на новую команду или вопрос по делу, а не на реплику в болтовне — её нужно разбирать обычным образом."""
    return bool(_CMD_VERB.search(norm(rest)))


def chat_turn(text: str, depth: int) -> tuple[str | None, bool]:
    """Реплика человека в болтовне → (ответ Карины, продолжать ли). None вместо ответа — это не болтовня, пусть разберут как команду."""
    t = norm(text)
    if is_command_like(t):
        return None, False
    kind = dialog.classify(t)
    if kind == "stop":
        return pick("cancel"), False
    if depth >= 2:
        return pick("chat_end"), False
    if _BAD.search(t):
        return pick("chat_bad" if depth == 0 else "chat_support"), depth == 0
    if _MEH.search(t):
        return pick("chat_meh"), True
    if _GOOD.search(t):
        return pick("chat_good"), True
    return pick("chat_more"), True

