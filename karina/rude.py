# Добавки к обычным ответам («Готово.», «Открываю…»): в дерзком режиме почти каждый ответ идёт с недовольством или матом.
OPENERS = ["Ну блин,", "Охуеть, опять я,", "Господи,", "Чёрт,", "Ладно, блядь,", "Ну конечно,", "Ой, всё,", "Заебал командовать, но ладно:", "Хрен с тобой,", "Опять ты со своим,"]
CLOSERS = ["Доволен, блин?", "Не благодари.", "Что-то ещё, или я свободна?", "Всё, отстань.", "Заебись, а?", "Следующая прихоть?", "Командир нашёлся, блин.",
           "Мог бы и сам кликнуть, лентяй.", "И так каждый раз, чёрт.", "Ну ты и барин, блядь."]
FAIL_START = ("не нашла", "не получилось", "ошибка", "не поняла", "не знаю", "нет интернета", "не выбрано", "не удалось", "окно «")


def pick(key: str, **kw) -> str:
    return random.choice(PHRASES[key]).format(**kw) if kw else random.choice(PHRASES[key])


def flavor(reply: str, chance: float = 0.7) -> str:
    """Обычный ответ + недовольство: «Готово.» → «Готово. Не благодари.». Не трогаем вопросы к человеку, ошибки и длинные ответы (их читают как есть)."""
    r = (reply or "").strip()
    if not r or len(r) > 140 or "?" in r or "«да»" in r.lower() or r.lower().startswith(FAIL_START) or random.random() > chance:
        return reply
    if random.random() < 0.5:
        return r + " " + random.choice(CLOSERS)
    low = r[0].lower() + r[1:] if r[:2].isalpha() and not r[1:2].isupper() else r
    return random.choice(OPENERS) + " " + low


# ---------------------------------------------------------------- повторный вопрос
class RepeatGuard:
    """Считает, сколько раз подряд (в течение окна) задан один и тот же вопрос. Похожие формулировки считаются одним вопросом."""

    def __init__(self, window: float = 900.0, similar: int = 88):
        self.window, self.similar = window, similar
        self._items: list[list] = []        # [текст, время последнего, сколько раз]

    def hit(self, text: str) -> int:
        """Записывает вопрос и возвращает, который это раз (1 — первый)."""
        t, now = norm(text), time.time()
        self._items = [x for x in self._items if now - x[1] < self.window]
        for x in self._items:
            if x[0] == t or fuzz.ratio(x[0], t) >= self.similar:
                x[1], x[2] = now, x[2] + 1
                return x[2]
        self._items.append([t, now, 1])
        return 1

    def reset(self):
        self._items.clear()


def repeat_reply(n: int) -> str | None:
    """Для 2-го, 3-го и дальше повторения — реплика; для первого — None."""
    if n <= 1:
        return None
    return pick("repeat_2" if n == 2 else "repeat_3" if n == 3 else "repeat_4")


