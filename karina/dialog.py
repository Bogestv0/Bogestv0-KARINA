"""Разбор коротких ответов на вопросы Карины: «да», «нет» или «стоп» (отмена).

Нужен всем местам, где она переспрашивает (включить VPN, искать в интернете, добавить приложение и т. д.): ответ принимается в любой
формулировке («да», «давай», «ага», «не надо», «стоп», «хватит», «замолчи»…), даже если вместе с ним Whisper услышал лишнее («Да. Не ко мне»).
Приоритет при смеси слов: стоп > нет > да — отменить безопаснее, чем выполнить.
"""
from __future__ import annotations
from .textutil import norm

YES = {"да", "дада", "давай", "давайте", "ага", "угу", "конечно", "разумеется", "естественно", "ок", "окей", "ладно", "хорошо", "верно", "правильно",
       "точно", "именно", "подтверждаю", "выполняй", "включай", "включи", "добавляй", "добавь", "поищи", "ищи", "искать", "согласна", "согласен",
       "yes", "ну да", "ага да", "так точно", "валяй", "действуй", "поехали", "го"}
NO = {"нет", "неа", "не", "ни", "ноу", "no", "отбой", "не надо", "не нужно", "не хочу", "не включай", "не добавляй", "не ищи", "не стоит", "наоборот"}
STOP = {"стоп", "стой", "хватит", "замолчи", "помолчи", "молчи", "тихо", "достаточно", "перестань", "прекрати", "довольно", "отмена", "отмени",
        "отменяй", "отменяю", "отставить", "забудь", "неважно", "ничего", "выйти", "выход", "закончили"}
FILLER = {"карина", "кариночка", "ну", "так", "эй", "пожалуйста", "уже", "все", "всё", "и", "а", "вот", "это", "тогда", "пока", "хм", "э", "эм", "мм"}

MAX_WORDS = 6        # ответ на вопрос — короткая фраза; длинная речь рядом — чаще всего фон, а не ответ


def classify(text: str) -> str | None:
    """→ "yes" | "no" | "stop" | None (не похоже на ответ)."""
    words = norm(text).split()
    words = [w for w in words if w not in FILLER or w in YES | NO | STOP]
    if not words or len(words) > MAX_WORDS:
        return None
    pairs = {" ".join(words[i:i + 2]) for i in range(len(words) - 1)}
    if any(w in STOP for w in words):
        return "stop"
    if any(w in NO for w in words) or pairs & NO:
        return "no"
    if any(w in YES for w in words) or pairs & YES:
        return "yes"
    return None


def is_yes(text: str) -> bool:
    return classify(text) == "yes"


def is_no(text: str) -> bool:
    return classify(text) in ("no", "stop")
